const assert=require('node:assert/strict');
const fs=require('node:fs');const vm=require('node:vm');
const host={innerWidth:390},doc={addEventListener(){}};
vm.runInNewContext(fs.readFileSync('chapter25.js','utf8'),{window:host,document:doc});
const cinema=host.SENDAS_CINEMA25;
assert.equal(cinema.version,'2.5.0');
assert.equal(cinema.fallbackFor('road3'),'olive');
assert.equal(cinema.fallbackFor('magdala3'),'dock');
assert.equal(cinema.fallbackFor('home'),'cover');
let points=cinema.hotspots('road3',{chapter22:{stage:2}});
assert.equal(points.length,2);assert.equal(points[0].id,'ch3:talk');
points=cinema.hotspots('road3',{chapter22:{roadChoice:'talk'}});
assert.equal(points[0].id,'ch3:magdala');
points=cinema.hotspots('magdala3',{chapter24:{}});
assert.equal(points.length,3);
assert.ok(points.every(p=>p.id.startsWith('m24:')));
assert.match(cinema.sceneStatus('magdala3',{chapter24:{clues:['origin','weights']}}),/2 de 4/);
assert.match(cinema.sceneStatus('magdala3',{chapter24:{compared:true}}),/Yael/);
assert.match(cinema.messageVisual('Una voz desde Magdala'),/messenger_courtyard\.webp/);
assert.equal(cinema.messageVisual('Otro encuentro'),'');
host.innerWidth=1024;
assert.equal(cinema.hotspots('magdala3',{chapter24:{}}).length,4);
console.log('PASS 2.5 scene fallbacks, interactions, responsiveness and messenger');